	public function on_group_cover_changed( $group_id ) {
		$this->sync_dir( $this->cover_dir( 'groups', (int) $group_id ), self::SOURCE_COVER, (int) $group_id );
	}

	/**
	 * Avatar URL from the bucket.
	 *
	 * @param string $url Local avatar URL.
	 * @return string
	 */
	public function filter_avatar_url( $url ) {
		if ( ! is_string( $url ) || '' === $url || ! $this->offloader->settings()->get( 'rewrite_urls' ) ) {
			return $url;
		}
		return $this->offloader->rewrite_url( $url );
	}

	/**
	 * Cover image URL from the bucket.
	 *
	 * BuddyBoss offers no URL-only filter for cover images:
	 * bp_attachments_pre_get_attachment runs for URL *and* path lookups
	 * without telling which one was requested. The requested type is
	 * therefore read from the calling frame; if that is not possible,
	 * BuddyBoss' default behaviour is kept.
	 *
	 * @param mixed $value Short-circuit value (null = default behaviour).
	 * @param array $args  Lookup arguments.
	 * @return mixed
	 */
	public function filter_cover_url( $value, $args ) {
		if ( null !== $value || $this->resolving_cover || ! $this->offloader->settings()->get( 'rewrite_urls' ) || 'url' !== (string) self::caller_argument( 'bp_attachments_get_attachment', 0, 'url' ) ) {
			return $value;
		}

		$this->resolving_cover = true;
		$url                   = bp_attachments_get_attachment( 'url', is_array( $args ) ? $args : array() );
		$this->resolving_cover = false;

		if ( ! is_string( $url ) || '' === $url ) {
			return $value;
		}

		$new = $this->offloader->rewrite_url( $url );
		return $new === $url ? $value : $new;
	}

	/**
	 * Argument of a running BuddyBoss function call.
	 *
	 * Some BuddyBoss filters do not receive all arguments of the function
	 * that applies them (bp_attachments_get_attachment()'s $data,
	 * bp_media_get_preview_image_url()'s $receiver_id). They are read from
	 * the calling frame; if that fails, $default is returned and BuddyBoss'
	 * default behaviour is kept.
	 *
	 * @param string $function_name Function name.
	 * @param int    $index         Argument index.
	 * @param mixed  $fallback      Value when the argument was not passed.
	 * @return mixed|null Null if the function is not on the call stack.
	 */
	private static function caller_argument( $function_name, $index, $fallback = null ) {
		// phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_debug_backtrace -- See method description.
		foreach ( debug_backtrace( 0, 12 ) as $frame ) {
			if ( isset( $frame['function'] ) && $function_name === $frame['function'] && empty( $frame['class'] ) ) {
				return isset( $frame['args'][ $index ] ) ? $frame['args'][ $index ] : $fallback;
			}
		}
		return null;
	}

	/**
	 * Queues a directory synchronisation for the end of the request.
	 *
	 * @param string $dir         Relative directory.
	 * @param string $source_type Source type.
	 * @param int    $source_id   Source ID.
	 * @return void
	 */
	private function queue_sync( $dir, $source_type, $source_id ) {
		if ( '' === $dir ) {
			return;
		}
		if ( empty( $this->sync_queue ) ) {
			add_action( 'shutdown', array( $this, 'process_sync_queue' ), 4 );
		}
		$this->sync_queue[ $dir ] = array( $source_type, (int) $source_id );
	}

	/**
	 * Processes queued directory synchronisations.
	 *
	 * @return void
	 */
	public function process_sync_queue() {
		$queue            = $this->sync_queue;
		$this->sync_queue = array();
		foreach ( $queue as $dir => $source ) {
			$this->sync_dir( $dir, $source[0], $source[1] );
		}
	}

	/**
	 * Mirrors a directory: uploads new/changed files and deletes objects whose
	 * local file is gone. Local files are always kept.
	 *
	 * @param string $dir         Relative directory.
	 * @param string $source_type Source type.
	 * @param int    $source_id   Source ID.
	 * @return array{uploaded:int,deleted:int,errors:int}
	 */
	public function sync_dir( $dir, $source_type, $source_id ) {
		$result = array(
			'uploaded' => 0,
			'deleted'  => 0,
			'errors'   => 0,
		);
		if ( '' === $dir || ! $this->offloader->settings()->is_configured() ) {
			return $result;
		}

		$local = array();
		$files = glob( $this->offloader->absolute( $dir ) . '/*' );
		foreach ( is_array( $files ) ? $files : array() as $file ) {
			if ( is_file( $file ) && 'index.php' !== basename( $file ) ) {
				$local[] = $dir . '/' . basename( $file );
			}
		}

		$stale = array_diff( array_keys( $this->offloader->items()->get_in_dir( $dir ) ), $local );
		if ( ! empty( $stale ) ) {
			$errors            = $this->offloader->delete_remote( $stale );
			$result['deleted'] = count( $stale ) - count( $errors );
			$result['errors'] += count( $errors );
		}

		if ( ! empty( $local ) ) {
			$upload             = $this->offloader->upload( $source_type, $source_id, $local, false );
			$result['uploaded'] = count( $upload['uploaded'] );
			$result['errors']  += count( $upload['errors'] );
		}

		return $result;
	}

	/**
	 * All avatar and cover directories (relative), for bulk synchronisation.
	 *
	 * The file system scan is cached for an hour, so a bulk run scans once.
	 *
	 * @param bool $refresh Rescan the file system.
	 * @return array<int,array{dir:string,type:string,id:int}>
	 */
	public function all_dirs( $refresh = false ) {
		$cached = $refresh ? false : get_transient( self::DIRS_CACHE );
		if ( is_array( $cached ) ) {
			return $cached;
		}
		$dirs = $this->scan_dirs();
		set_transient( self::DIRS_CACHE, $dirs, HOUR_IN_SECONDS );
		return $dirs;
	}

	/**
	 * Scans the file system for avatar and cover directories.
	 *
	 * @return array<int,array{dir:string,type:string,id:int}>
	 */
	private function scan_dirs() {
		$dirs = array();
		if ( ! function_exists( 'bp_core_avatar_upload_path' ) ) {
			return $dirs;
		}

		$patterns = array(
			array( bp_core_avatar_upload_path() . '/avatars/*', self::SOURCE_AVATAR ),
			array( bp_core_avatar_upload_path() . '/group-avatars/*', self::SOURCE_AVATAR ),
		);
		if ( function_exists( 'bp_attachments_uploads_dir_get' ) ) {
			$base       = bp_attachments_uploads_dir_get( 'basedir' );
			$patterns[] = array( $base . '/members/*/cover-image', self::SOURCE_COVER );
			$patterns[] = array( $base . '/groups/*/cover-image', self::SOURCE_COVER );
		}

		foreach ( $patterns as $pattern ) {
			$found = glob( $pattern[0], GLOB_ONLYDIR );
			foreach ( is_array( $found ) ? $found : array() as $abs ) {
				$relative = $this->offloader->relative( $abs );
				// Skip the "0" directories of BuddyBoss' default images.
				$id = (int) basename( self::SOURCE_COVER === $pattern[1] ? dirname( $abs ) : $abs );
				if ( '' !== $relative && $id > 0 ) {
					$dirs[] = array(
						'dir'  => $relative,
						'type' => $pattern[1],
						'id'   => $id,
					);
				}
			}
		}

		return $dirs;
	}
