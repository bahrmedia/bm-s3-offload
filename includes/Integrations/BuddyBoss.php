/**
 * Covers BuddyBoss photos, documents and videos (activity, groups, forums,
 * messages), member and group avatars and cover images.
 *
 * Privacy model: files in bb_medias/, bb_documents/ and bb_videos/ are stored
 * as private objects. They are only delivered through
 *  - BuddyBoss' own preview endpoints, which we answer with a redirect to a
 *    short-lived signed URL after BuddyBoss' access check ("proxy" mode), or
 *  - signed URLs embedded directly in pages that BuddyBoss has already
 *    filtered by privacy ("direct" mode, faster, URLs expire).
 *
 * Avatars and cover images are public in BuddyBoss. They are mirrored to
 * the bucket and served from there, but the local copies are kept because
 * BuddyBoss detects them by scanning the file system.
 */
final class BuddyBoss {

	const SOURCE_AVATAR = 'bb_avatar';
	const SOURCE_COVER  = 'bb_cover';
	const DIRS_CACHE    = 'bms3o_bb_dirs';

	/**
	 * Offloader.
	 *
	 * @var Offloader
	 */
	private $offloader;

	/**
	 * Attachments module.
	 *
	 * @var Attachments
	 */
	private $attachments;

	/**
	 * Directories to synchronise at the end of the request.
	 *
	 * @var array<string,array{0:string,1:int}>
	 */
	private $sync_queue = array();

	/**
	 * Recursion guard for cover lookups.
	 *
	 * @var bool
	 */
	private $resolving_cover = false;

	/**
	 * Constructor.
	 *
	 * @param Offloader   $offloader   Offloader.
	 * @param Attachments $attachments Attachments module.
	 */
	public function __construct( Offloader $offloader, Attachments $attachments ) {
		$this->offloader   = $offloader;
		$this->attachments = $attachments;
	}

	/**
	 * Whether BuddyBoss Platform is active.
	 *
	 * @return bool
	 */
	public static function is_active() {
		return defined( 'BP_PLATFORM_VERSION' );
	}

	/**
	 * Registers hooks.
	 *
	 * @return void
	 */
	public function register() {
		$settings = $this->offloader->settings();
		if ( ! $settings->get( 'bb_enabled' ) ) {
			return;
		}

		// BuddyBoss' download functions are only reached after its can_download check.
		add_filter( 'bms3o_can_access_private', array( $this, 'filter_access_in_download' ), 10, 2 );

		// Photos, documents, videos: deliver from the bucket instead of local symlinks.
		foreach ( array( 'bb_media_do_symlink', 'bb_document_do_symlink', 'bb_video_do_symlink', 'bb_video_create_thumb_symlinks' ) as $filter ) {
			add_filter( $filter, array( $this, 'filter_do_symlink' ), 99, 3 );
		}
		add_filter( 'bp_media_get_preview_image_url', array( $this, 'filter_media_preview_url' ), 99, 5 );
		add_filter( 'bp_document_get_preview_url', array( $this, 'filter_document_preview_url' ), 99, 6 );
		add_filter( 'bb_video_get_thumb_url', array( $this, 'filter_video_thumb_url' ), 99, 5 );
		add_filter( 'bb_video_get_symlink', array( $this, 'filter_video_url' ), 99, 4 );

		// BuddyBoss preview endpoints: redirect to signed URLs after the access check.
		add_action( 'bb_setup_template_for_media_preview', array( $this, 'redirect_media_preview' ) );
		add_action( 'bb_setup_attachment_media_preview_template', array( $this, 'redirect_attachment_preview' ) );

		// Thumbnails regenerated by BuddyBoss need the original locally.
		add_action( 'bp_core_before_regenerate_attachment_thumbnails', array( $this, 'before_regenerate' ) );
		add_action( 'bp_core_after_regenerate_attachment_thumbnails', array( $this, 'after_regenerate' ) );

		// Tell BuddyBoss that media is offloaded.
		add_filter( 'bb_media_offload_delivered', array( $this, 'filter_offload_delivered' ) );
		add_filter( 'bb_media_check_default_access', array( $this, 'filter_offload_delivered' ) );
		add_filter( 'bb_media_offload_delivery_provider', array( $this, 'filter_delivery_provider' ) );
		add_filter( 'bp_core_get_js_strings', array( $this, 'filter_js_strings' ) );

		if ( $settings->get( 'bb_avatars' ) ) {
			$this->register_avatar_hooks();
		}
	}

	/**
	 * Avatar and cover image hooks.
	 *
	 * @return void
	 */
	private function register_avatar_hooks() {
		add_action( 'xprofile_avatar_uploaded', array( $this, 'on_user_avatar_uploaded' ), 20, 1 );
		add_action( 'groups_avatar_uploaded', array( $this, 'on_group_avatar_uploaded' ), 20, 1 );
		add_filter( 'bp_core_pre_delete_existing_avatar', array( $this, 'on_avatar_delete' ), 20, 2 );

		add_action( 'xprofile_cover_image_uploaded', array( $this, 'on_user_cover_changed' ), 5, 1 );
		add_action( 'xprofile_cover_image_deleted', array( $this, 'on_user_cover_changed' ), 5, 1 );
		add_action( 'groups_cover_image_uploaded', array( $this, 'on_group_cover_changed' ), 5, 1 );
		add_action( 'groups_cover_image_deleted', array( $this, 'on_group_cover_changed' ), 5, 1 );

		// Priority below 1000: moderation (suspended members) must still be able to override.
		add_filter( 'bp_core_fetch_avatar_url_check', array( $this, 'filter_avatar_url' ), 50, 1 );
		add_filter( 'bp_attachments_pre_get_attachment', array( $this, 'filter_cover_url' ), 50, 2 );
	}

	/*
	 * ------------------------------------------------------------------
	 * Photos, documents, videos
	 * ------------------------------------------------------------------
	 */

	/**
	 * Allows a signed URL for a restricted file while BuddyBoss' own download
	 * function requests it. BuddyBoss calls these functions only after its
	 * access check (private network, can_download for this attachment).
	 *
	 * @param bool  $allowed Current value.
	 * @param array $item    Item row.
	 * @return bool
	 */
	public function filter_access_in_download( $allowed, $item ) {
		if ( $allowed ) {
			return true;
		}
		foreach ( array( 'bp_media_download_file', 'bp_document_download_file', 'bb_document_download_file', 'bp_video_download_file', 'bb_video_download_file' ) as $function_name ) {
			$attachment_id = self::caller_argument( $function_name, 0 );
			if ( null !== $attachment_id ) {
				// Only the attachment BuddyBoss is serving.
				return isset( $item['source_type'], $item['source_id'] ) && 'attachment' === $item['source_type'] && (int) $attachment_id === (int) $item['source_id'];
			}
		}
		return $allowed;
	}

	/**
	 * Whether an attachment is delivered from the bucket.
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return bool
	 */
	private function delivers( $attachment_id ) {
		$item = $attachment_id ? $this->attachments->main_item( (int) $attachment_id ) : null;
		return $item && ( $item['local_removed'] || $this->offloader->settings()->get( 'rewrite_urls' ) );
	}

	/**
	 * Disables local symlinks for offloaded files.
	 *
	 * @param bool $do_symlink    Current value.
	 * @param int  $id            Media/document/video ID.
	 * @param int  $attachment_id Attachment ID.
	 * @return bool
	 */
	public function filter_do_symlink( $do_symlink, $id, $attachment_id ) {
		return $this->delivers( (int) $attachment_id ) ? false : $do_symlink;
	}

	/**
	 * URL of an attachment size (signed for private objects).
	 *
	 * @param int    $attachment_id Attachment ID.
	 * @param string $size          Size name ('' or 'full' = original).
	 * @return string
	 */
	private function size_url( $attachment_id, $size ) {
		return $this->offloader->with_private_access(
			static function () use ( $attachment_id, $size ) {
				$meta = wp_get_attachment_metadata( $attachment_id );
				if ( '' !== $size && 'full' !== $size && isset( $meta['sizes'][ $size ] ) ) {
					$url = wp_get_attachment_image_url( $attachment_id, $size );
					if ( $url ) {
						return $url;
					}
				}
				return (string) wp_get_attachment_url( $attachment_id );
			}
		);
	}

	/**
	 * Original file URL (signed for private objects).
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return string
	 */
	private function file_url( $attachment_id ) {
		return $this->offloader->with_private_access(
			static function () use ( $attachment_id ) {
				return (string) wp_get_attachment_url( $attachment_id );
			}
		);
	}

	/**
	 * Photo preview URL.
	 *
	 * @param string $url           URL computed by BuddyBoss.
	 * @param int    $media_id      Media ID.
	 * @param int    $attachment_id Attachment ID.
	 * @param string $size          Size.
	 * @return string
	 */
	public function filter_media_preview_url( $url, $media_id, $attachment_id, $size ) {
		if ( ! $this->delivers( (int) $attachment_id ) ) {
			return $url;
		}

		if ( 'proxy' === $this->offloader->settings()->get( 'bb_delivery' ) ) {
			// Same format as BuddyBoss' own preview endpoint; answered by redirect_media_preview().
			$media_segment      = 'forbidden_' . (int) $media_id;
			$attachment_segment = 'forbidden_' . (int) $attachment_id;
			// phpcs:disable WordPress.PHP.DiscouragedPHPFunctions.obfuscation_base64_encode -- BuddyBoss URL format.
			$url = home_url( '/' ) . 'bb-media-preview/' . base64_encode( $attachment_segment ) . '/' . base64_encode( $media_segment ) . '/' . rawurlencode( (string) $size );
			// phpcs:enable

			// E-mails pass a receiver: add BuddyBoss' signed receiver segment, as BuddyBoss does.
			$receiver_id = (int) self::caller_argument( 'bp_media_get_preview_image_url', 4 );
			if ( $receiver_id > 0 && function_exists( 'bb_media_preview_receiver_segment' ) ) {
				$url .= '/' . bb_media_preview_receiver_segment( $receiver_id, $media_segment, $attachment_segment );
			}

			return untrailingslashit( $url );
		}

		return $this->size_url( (int) $attachment_id, (string) $size );
	}

	/**
	 * Document preview URL (preview images of PDFs etc. and audio files).
	 *
	 * @param string $url           URL computed by BuddyBoss.
	 * @param int    $document_id   Document ID.
	 * @param string $extension     File extension.
	 * @param string $size          Size.
	 * @param int    $attachment_id Attachment ID.
	 * @return string
	 */
	public function filter_document_preview_url( $url, $document_id, $extension, $size, $attachment_id ) {
		if ( ! $this->delivers( (int) $attachment_id ) ) {
			return $url;
		}

		$extension = strtolower( (string) $extension );

		if ( function_exists( 'bp_get_document_preview_music_extensions' ) && in_array( $extension, (array) bp_get_document_preview_music_extensions(), true ) ) {
			return $this->file_url( (int) $attachment_id );
		}

		if ( function_exists( 'bp_get_document_preview_doc_extensions' ) && in_array( $extension, (array) bp_get_document_preview_doc_extensions(), true ) ) {
			$meta = wp_get_attachment_metadata( $attachment_id );
			foreach ( array( (string) $size, 'full' ) as $candidate ) {
				if ( '' !== $candidate && isset( $meta['sizes'][ $candidate ] ) ) {
					return $this->size_url( (int) $attachment_id, $candidate );
				}
			}
			return wp_attachment_is_image( $attachment_id ) ? $this->file_url( (int) $attachment_id ) : $url;
		}

		return $url;
	}

	/**
	 * Video thumbnail URL.
	 *
	 * @param string $url           URL computed by BuddyBoss.
	 * @param int    $video_id      Video ID.
	 * @param string $size          Size.
	 * @param int    $attachment_id Thumbnail attachment ID.
	 * @return string
	 */
	public function filter_video_thumb_url( $url, $video_id, $size, $attachment_id ) {
		return $this->delivers( (int) $attachment_id ) ? $this->size_url( (int) $attachment_id, (string) $size ) : $url;
	}

	/**
	 * Video file URL.
	 *
	 * @param string $url           URL computed by BuddyBoss.
	 * @param int    $video_id      Video ID.
	 * @param int    $attachment_id Attachment ID.
	 * @return string
	 */
	public function filter_video_url( $url, $video_id, $attachment_id ) {
		return $this->delivers( (int) $attachment_id ) ? $this->file_url( (int) $attachment_id ) : $url;
	}

	/**
	 * Answers /bb-media-preview/… with a redirect to a signed URL.
	 *
	 * Mirrors the access check of BuddyBoss' preview template
	 * (bp-templates/bp-nouveau/includes/media/preview.php). Anything not
	 * handled here falls through to BuddyBoss.
	 *
	 * @return void
	 */
	public function redirect_media_preview() {
		$attachment_id = self::decode_id( get_query_var( 'bb-media-preview' ), 'forbidden_' );
		$media_id      = self::decode_id( get_query_var( 'id1' ), 'forbidden_' );
		if ( ! $attachment_id || ! $media_id || ! $this->delivers( $attachment_id ) || ! function_exists( 'bb_media_user_can_access' ) ) {
			return;
		}

		// E-mail links carry a signed receiver segment: act as that receiver (as BuddyBoss does).
		if ( function_exists( 'bb_media_preview_get_receiver_id' ) ) {
			$receiver_id = (int) bb_media_preview_get_receiver_id( get_query_var( 'receiver' ), $media_id, $attachment_id );
			if ( $receiver_id > 0 ) {
				wp_set_current_user( $receiver_id );
				add_filter(
					'bp_loggedin_user_id',
					static function () use ( $receiver_id ) {
						return $receiver_id;
					}
				);
			}
		}

		$access = bb_media_user_can_access( $media_id, 'photo', $attachment_id );
		if ( empty( $access['can_view'] ) || ! wp_attachment_is_image( $attachment_id ) ) {
			return;
		}

		$this->redirect( $this->size_url( $attachment_id, (string) get_query_var( 'size' ) ) );
	}

	/**
	 * Answers /bb-attachment-media-preview/… (uploads before saving, messages).
	 *
	 * Mirrors bp-templates/bp-nouveau/includes/media/attachment.php.
	 *
	 * @return void
	 */
	public function redirect_attachment_preview() {
		global $wpdb;

		$attachment_id = self::decode_id( get_query_var( 'media-attachment-id' ), 'forbidden_' );
		if ( ! $attachment_id || ! $this->delivers( $attachment_id ) || ! function_exists( 'buddypress' ) || empty( buddypress()->media->table_name ) ) {
			return;
		}

		$table = buddypress()->media->table_name;
		// phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared,WordPress.DB.DirectDatabaseQuery,WordPress.DB.DirectDatabaseQuery.NoCaching
		$media = $wpdb->get_row( $wpdb->prepare( "SELECT id FROM {$table} WHERE attachment_id = %d AND type = %s", $attachment_id, 'photo' ) );

		if ( $media ) {
			$thread_id = self::decode_id( get_query_var( 'media-thread-id' ), 'thread_' );
			if ( ! $thread_id || ! function_exists( 'bb_media_user_can_access' ) ) {
				return;
			}
			$access = bb_media_user_can_access( (int) $media->id, 'photo', $attachment_id );
			if ( empty( $access['can_view'] ) ) {
				return;
			}
		} else {
			// Unsaved uploads are only visible to their uploader (and moderators).
			$is_upload = (bool) get_post_meta( $attachment_id, 'bp_media_upload', true );
			$is_owner  = (int) get_post_field( 'post_author', $attachment_id ) === (int) get_current_user_id();
			$moderator = function_exists( 'bp_current_user_can' ) && bp_current_user_can( 'bp_moderate' );
			if ( ! $is_upload || ! is_user_logged_in() || ( ! $is_owner && ! $moderator ) ) {
				return;
			}
		}

		if ( ! wp_attachment_is_image( $attachment_id ) ) {
			return;
		}

		$this->redirect( $this->size_url( $attachment_id, (string) get_query_var( 'size' ) ) );
	}

	/**
	 * Sends a non-cacheable redirect and ends the request.
	 *
	 * @param string $url Target URL.
	 * @return void
	 */
	private function redirect( $url ) {
		if ( '' === $url ) {
			return;
		}
		nocache_headers();
		// phpcs:ignore WordPress.Security.SafeRedirect.wp_redirect_wp_redirect -- Redirect to the configured bucket / CDN host.
		wp_redirect( $url, 302, 'BM S3 Offload' );
		exit;
	}

	/**
	 * Decodes a BuddyBoss base64 ID segment such as base64("forbidden_123").
	 *
	 * @param mixed  $value  Query var.
	 * @param string $prefix Prefix inside the encoded value.
	 * @return int
	 */
	private static function decode_id( $value, $prefix ) {
		if ( ! is_string( $value ) || '' === $value ) {
			return 0;
		}
		// phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.obfuscation_base64_decode -- BuddyBoss URL format.
		$decoded = base64_decode( $value, true );
		if ( false === $decoded || 0 !== strpos( $decoded, $prefix ) ) {
			return 0;
		}
		return max( 0, (int) substr( $decoded, strlen( $prefix ) ) );
	}

	/**
	 * Before BuddyBoss regenerates thumbnails.
	 *
	 * @return void
	 */
	public function before_regenerate() {
		$this->attachments->set_regenerating( true );
	}

	/**
	 * After BuddyBoss regenerated thumbnails.
	 *
	 * @return void
	 */
	public function after_regenerate() {
		$this->attachments->set_regenerating( false );
	}

	/**
	 * Reports offloaded delivery to BuddyBoss (disables its symlink option and
	 * the local direct-access check in the media settings).
	 *
	 * @param bool $value Current value.
	 * @return bool
	 */
	public function filter_offload_delivered( $value ) {
		return $this->offloader->settings()->is_configured() ? true : $value;
	}

	/**
	 * Provider name shown by BuddyBoss.
	 *
	 * @param string $provider Current value.
	 * @return string
	 */
	public function filter_delivery_provider( $provider ) {
		if ( ! $this->offloader->settings()->is_configured() ) {
			return $provider;
		}
		return 'BM S3 Offload (' . Providers::label( $this->offloader->settings()->get( 'provider' ) ) . ')';
	}

	/**
	 * Lets the BuddyBoss frontend use server-side thumbnails instead of
	 * loading bucket images into a canvas (which would require CORS).
	 *
	 * @param array $params JS strings.
	 * @return array
	 */
	public function filter_js_strings( $params ) {
		if ( is_array( $params ) && function_exists( 'bp_is_active' ) && bp_is_active( 'activity' ) && bp_is_active( 'media' ) && $this->offloader->settings()->is_configured() ) {
			$params['is_as3cf_active'] = true;
		}
		return $params;
	}

