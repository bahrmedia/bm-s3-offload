	/**
	 * Relative avatar directory of an object.
	 *
	 * @param string      $object_type 'user', 'group' or 'blog'.
	 * @param int         $item_id     Object ID.
	 * @param string|bool $avatar_dir  Custom avatar directory.
	 * @return string '' if outside the uploads directory.
	 */
	private function avatar_dir( $object_type, $item_id, $avatar_dir = false ) {
		if ( ! function_exists( 'bp_core_avatar_upload_path' ) || ! $item_id ) {
			return '';
		}
		if ( ! $avatar_dir ) {
			$dirs       = array(
				'user'  => 'avatars',
				'group' => 'group-avatars',
				'blog'  => 'blog-avatars',
			);
			$avatar_dir = isset( $dirs[ $object_type ] ) ? $dirs[ $object_type ] : $object_type . '-avatars';
		}
		return $this->offloader->relative( bp_core_avatar_upload_path() . '/' . $avatar_dir . '/' . (int) $item_id );
	}

	/**
	 * Relative cover image directory.
	 *
	 * @param string $object_dir 'members' or 'groups'.
	 * @param int    $item_id    Object ID.
	 * @return string
	 */
	private function cover_dir( $object_dir, $item_id ) {
		if ( ! function_exists( 'bp_attachments_uploads_dir_get' ) || ! $item_id ) {
			return '';
		}
		return $this->offloader->relative( bp_attachments_uploads_dir_get( 'basedir' ) . '/' . $object_dir . '/' . (int) $item_id . '/cover-image' );
	}

	/**
	 * User avatar uploaded/cropped.
	 *
	 * @param int $user_id User ID.
	 * @return void
	 */
	public function on_user_avatar_uploaded( $user_id ) {
		$this->sync_dir( $this->avatar_dir( 'user', (int) $user_id ), self::SOURCE_AVATAR, (int) $user_id );
	}

	/**
	 * Group avatar uploaded/cropped.
	 *
	 * @param int $group_id Group ID.
	 * @return void
	 */
	public function on_group_avatar_uploaded( $group_id ) {
		$this->sync_dir( $this->avatar_dir( 'group', (int) $group_id ), self::SOURCE_AVATAR, (int) $group_id );
	}

	/**
	 * Avatar about to be deleted: synchronise the directory at the end of the request.
	 *
	 * @param bool  $proceed Whether BuddyBoss proceeds.
	 * @param array $args    Delete arguments.
	 * @return bool
	 */
	public function on_avatar_delete( $proceed, $args ) {
		$args    = is_array( $args ) ? $args : array();
		$object  = isset( $args['object'] ) ? (string) $args['object'] : 'user';
		$item_id = isset( $args['item_id'] ) ? (int) $args['item_id'] : 0;

		if ( ! $item_id ) {
			if ( 'user' === $object && function_exists( 'bp_displayed_user_id' ) ) {
				$item_id = (int) bp_displayed_user_id();
			} elseif ( 'group' === $object && function_exists( 'buddypress' ) && isset( buddypress()->groups->current_group->id ) ) {
				$item_id = (int) buddypress()->groups->current_group->id;
			}
		}

		$dir = $this->avatar_dir( $object, $item_id, isset( $args['avatar_dir'] ) ? $args['avatar_dir'] : false );
		$this->queue_sync( $dir, self::SOURCE_AVATAR, $item_id );

		return $proceed;
	}

