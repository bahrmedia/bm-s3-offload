/**
 * Offloads attachments (original, all sizes, the unscaled original and
 * edit backups) and serves them from the bucket.
 */
final class Attachments {

	const RETRY_OPTION = 'bms3o_retry';

	/**
	 * Option: shared files whose items could not be handed over to the
	 * remaining attachment (path => main file), retried hourly.
	 */
	const HANDOVER_OPTION = 'bms3o_handover';

	/**
	 * Cron hook that offloads large attachments after the upload request.
	 */
	const ASYNC_HOOK = 'bms3o_offload_attachment';

	/**
	 * Attachments larger than this (all files together) are offloaded in the
	 * background, so big videos do not hit the time limit of the upload request.
	 */
	const ASYNC_THRESHOLD = 67108864; // 64 MiB.

	/**
	 * Protected upload directories: BuddyBoss photos, documents and videos,
	 * WooCommerce and Easy Digital Downloads product files. Files in there are
	 * protected by those plugins and are therefore stored privately with
	 * restricted access - also when an integration is switched off.
	 */
	const PROTECTED_DIRS = array( 'bb_medias/', 'bb_documents/', 'bb_videos/', 'woocommerce_uploads/', 'edd/' );

	/**
	 * Protected directories whose plugins have no delivery integration yet:
	 * offloaded as private backup, but the local copies are always kept.
	 */
	const KEEP_LOCAL_DIRS = array( 'edd/' );

	/**
	 * Post meta: per-attachment privacy chosen in the media library ('1' or '0').
	 */
	const META_PRIVATE = '_bms3o_private';
	const MAX_ATTEMPTS = 5;

	/**
	 * Offloader.
	 *
	 * @var Offloader
	 */
	private $offloader;

	/**
	 * True while thumbnails are being regenerated by a third party.
	 *
	 * @var bool
	 */
	private $regenerating = false;

	/**
	 * Attachments that were restored temporarily and must end up bucket-only again.
	 *
	 * @var array<int,true>
	 */
	private $restored = array();

	/**
	 * While > 0, attachment URLs stay local (e.g. while a plugin searches the
	 * local URLs stored in content to replace them).
	 *
	 * @var int
	 */
	private $local_urls = 0;

	/**
	 * Constructor.
	 *
	 * @param Offloader $offloader Offloader.
	 */
	public function __construct( Offloader $offloader ) {
		$this->offloader = $offloader;
	}

	/**
	 * Registers hooks.
	 *
	 * @return void
	 */
	public function register() {
		// Upload / edit / delete.
		add_filter( 'wp_update_attachment_metadata', array( $this, 'on_update_metadata' ), 110, 2 );
		add_action( 'delete_attachment', array( $this, 'on_delete' ), 5 );
		add_filter( 'wp_unique_filename', array( $this, 'filter_unique_filename' ), 10, 3 );
		add_filter( 'bms3o_private_is_restricted', array( $this, 'filter_private_is_restricted' ), 10, 2 );

		// Delivery.
		add_filter( 'wp_get_attachment_url', array( $this, 'filter_attachment_url' ), 99, 2 );
		add_filter( 'image_downsize', array( $this, 'filter_image_downsize' ), 99, 3 );
		add_filter( 'wp_calculate_image_srcset', array( $this, 'filter_srcset' ), 99, 5 );
		add_filter( 'the_posts', array( $this, 'prime_posts' ), 10, 1 );

		// Local copies on demand.
		add_filter( 'load_image_to_edit_path', array( $this, 'filter_edit_path' ), 5, 3 );
		add_filter( 'wp_get_original_image_path', array( $this, 'filter_original_image_path' ), 5, 2 );

		// Retries and background offloads.
		add_action( 'bms3o_cron', array( $this, 'retry_failed' ) );
		add_action( 'bms3o_cron', array( $this, 'retry_handovers' ) );
		add_action( self::ASYNC_HOOK, array( $this, 'offload_in_background' ) );
	}

	/*
	 * ------------------------------------------------------------------
	 * Paths
	 * ------------------------------------------------------------------
	 */

	/**
	 * All relative paths of an attachment.
	 *
	 * @param int        $attachment_id Attachment ID.
	 * @param array|null $meta          Metadata (defaults to stored metadata).
	 * @return string[]
	 */
	public function paths( $attachment_id, $meta = null ) {
		$file = (string) get_post_meta( $attachment_id, '_wp_attached_file', true );
		if ( '' === $file || 0 === strpos( $file, '/' ) || false !== strpos( $file, '://' ) || preg_match( '#^[a-zA-Z]:\\\\#', $file ) ) {
			return array(); // Missing, absolute or external file.
		}

		if ( null === $meta ) {
			$meta = wp_get_attachment_metadata( $attachment_id, true );
		}
		$meta  = is_array( $meta ) ? $meta : array();
		$dir   = dirname( $file );
		$dir   = ( '.' === $dir || '' === $dir ) ? '' : $dir . '/';
		$paths = array( $file );

		if ( ! empty( $meta['sizes'] ) && is_array( $meta['sizes'] ) ) {
			foreach ( $meta['sizes'] as $size ) {
				if ( ! empty( $size['file'] ) ) {
					$paths[] = $dir . $size['file'];
				}
			}
		}

		if ( ! empty( $meta['original_image'] ) ) {
			$paths[] = $dir . $meta['original_image'];
		}

		$backups = get_post_meta( $attachment_id, '_wp_attachment_backup_sizes', true );
		if ( is_array( $backups ) ) {
			foreach ( $backups as $backup ) {
				if ( ! empty( $backup['file'] ) ) {
					$paths[] = $dir . $backup['file'];
				}
			}
		}

		// WebP/AVIF copies of image optimisers that append the extension (EWWW, WebP Express: photo.jpg.webp).
		$sidecars = array();
		foreach ( $paths as $path ) {
			$sidecars[] = $path . '.webp';
			$sidecars[] = $path . '.avif';
		}
		$known      = $this->offloader->items()->get_many( $sidecars );
		$candidates = array();
		foreach ( $sidecars as $sidecar ) {
			if ( isset( $known[ $sidecar ] ) ) {
				// Only our own sidecars, never another source's file.
				if ( Items::SOURCE_POST === $known[ $sidecar ]['source_type'] && (int) $attachment_id === $known[ $sidecar ]['source_id'] ) {
					$paths[] = $sidecar;
				}
			} elseif ( is_file( $this->offloader->absolute( $sidecar ) ) ) {
				$candidates[] = $sidecar;
			}
		}
		// A file like "photo.jpg.webp" may also be an attachment of its own.
		$paths = array_merge( $paths, array_diff( $candidates, self::attached_files( $candidates ) ) );

		/**
		 * Filters the files that belong to an attachment.
		 *
		 * @param string[] $paths         Paths relative to the uploads directory.
		 * @param int      $attachment_id Attachment ID.
		 * @param array    $meta          Attachment metadata.
		 */
		$paths = (array) apply_filters( 'bms3o_attachment_paths', $paths, $attachment_id, $meta );

		return array_values( array_unique( array_filter( $paths, 'strlen' ) ) );
	}

	/**
	 * Which of the given relative paths are the main file of an attachment.
	 *
	 * @param string[] $paths Relative paths.
	 * @return string[]
	 */
	private static function attached_files( array $paths ) {
		global $wpdb;
		if ( empty( $paths ) ) {
			return array();
		}
		$placeholders = implode( ',', array_fill( 0, count( $paths ), '%s' ) );
		// phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared,WordPress.DB.DirectDatabaseQuery,WordPress.DB.PreparedSQLPlaceholders.UnfinishedPrepare
		$found = $wpdb->get_col( $wpdb->prepare( "SELECT meta_value FROM {$wpdb->postmeta} WHERE meta_key = '_wp_attached_file' AND meta_value IN ({$placeholders})", $paths ) );
		return array_map( 'strval', (array) $found );
	}

	/**
	 * Whether an attachment is stored as private object.
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return bool
	 */
	public function is_private( $attachment_id ) {
		$file = (string) get_post_meta( $attachment_id, '_wp_attached_file', true );
		// BuddyBoss media follow the "private media" setting, shop downloads are always private.
		$is_private = $this->is_protected_path( $file ) && ( 0 !== strpos( $file, 'bb_' ) || $this->offloader->settings()->get( 'bb_private' ) );

		$override = get_post_meta( $attachment_id, self::META_PRIVATE, true );
		if ( '1' === $override ) {
			$is_private = true;
		} elseif ( '0' === $override && ! $this->is_protected_path( $file ) ) {
			$is_private = false;
		}

		/**
		 * Filters whether an attachment is stored privately and served with signed URLs only.
		 *
		 * @param bool   $is_private    Default: true for protected directories and media marked private.
		 * @param int    $attachment_id Attachment ID.
		 * @param string $file          Relative path of the main file.
		 */
		return (bool) apply_filters( 'bms3o_attachment_is_private', $is_private, $attachment_id, $file );
	}

	/**
	 * Whether a relative path is inside a protected upload directory.
	 *
	 * @param string $path Relative path.
	 * @return bool
	 */
	public function is_protected_path( $path ) {
		foreach ( self::PROTECTED_DIRS as $dir ) {
			if ( 0 === strpos( (string) $path, $dir ) ) {
				return true;
			}
		}
		return false;
	}

	/**
	 * Directories of plugins whose files are only delivered from the bucket by
	 * the matching integration, with a label for notices.
	 *
	 * @return array<string,array{dirs:string[],label:string,active:bool}>
	 */
	public function integration_dirs() {
		$settings = $this->offloader->settings();
		return array(
			'woocommerce' => array(
				'dirs'   => array( 'woocommerce_uploads/' ),
				'label'  => __( 'WooCommerce downloads', 'bm-s3-offload' ),
				'active' => WooCommerce::is_active() && (bool) $settings->get( 'wc_enabled' ),
			),
			'buddyboss'   => array(
				'dirs'   => array( 'bb_medias/', 'bb_documents/', 'bb_videos/' ),
				'label'  => __( 'BuddyBoss media', 'bm-s3-offload' ),
				'active' => BuddyBoss::is_active() && (bool) $settings->get( 'bb_enabled' ),
			),
		);
	}

	/**
	 * Whether a file can be delivered while its local copy is missing: always,
	 * except for directories whose integration is inactive or switched off.
	 *
	 * @param string $path Relative path.
	 * @return bool
	 */
	public function delivered_from_bucket( $path ) {
		foreach ( $this->integration_dirs() as $integration ) {
			foreach ( $integration['dirs'] as $dir ) {
				if ( 0 === strpos( (string) $path, $dir ) ) {
					return $integration['active'];
				}
			}
		}
		return true;
	}

	/**
	 * Warnings about files that exist only in the bucket although their
	 * integration is inactive (they cannot be delivered then).
	 *
	 * @return string[]
	 */
	public function undeliverable_warnings() {
		$warnings = array();
		foreach ( $this->integration_dirs() as $integration ) {
			if ( $integration['active'] ) {
				continue;
			}
			$count = 0;
			foreach ( $integration['dirs'] as $dir ) {
				$count += $this->offloader->items()->count_bucket_only( $dir );
			}
			if ( $count > 0 ) {
				$warnings[] = sprintf(
					/* translators: 1: number of files, 2: e.g. "WooCommerce downloads" */
					_n(
						'%1$d file of the %2$s exists only in the bucket, but the integration is inactive or switched off, so it cannot be delivered. Switch the integration on or run "Restore local copies" in the tools tab.',
						'%1$d files of the %2$s exist only in the bucket, but the integration is inactive or switched off, so they cannot be delivered. Switch the integration on or run "Restore local copies" in the tools tab.',
						$count,
						'bm-s3-offload'
					),
					$count,
					$integration['label']
				);
			}
		}
		return $warnings;
	}

	/**
	 * Only files in protected directories need an access check; other private
	 * media are delivered with expiring signed URLs.
	 *
	 * @param bool  $restricted Current value.
	 * @param array $item       Item row.
	 * @return bool
	 */
	public function filter_private_is_restricted( $restricted, $item ) {
		if ( isset( $item['source_type'], $item['path'] ) && Items::SOURCE_POST === $item['source_type'] ) {
			return $this->is_protected_path( $item['path'] );
		}
		return $restricted;
	}

	/**
	 * Whether BuddyBoss media are stored privately (setting).
	 *
	 * @return bool
	 */
	public function buddyboss_private() {
		return (bool) $this->offloader->settings()->get( 'bb_private' );
	}

	/**
	 * Moves the objects of an attachment to the privacy it should have now
	 * (e.g. after the "private media" setting was changed).
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return array<string,string> Errors by path.
	 */
	public function sync_privacy( $attachment_id ) {
		$target = $this->is_private( (int) $attachment_id );
		$paths  = array();
		foreach ( $this->offloader->items()->get_by_source( Items::SOURCE_POST, (int) $attachment_id ) as $path => $item ) {
			if ( (bool) $item['is_private'] !== $target ) {
				$paths[] = $path;
			}
		}
		return empty( $paths ) ? array() : $this->offloader->set_privacy( $paths, $target );
	}

	/**
	 * Makes an attachment private (expiring signed URLs) or public.
	 *
	 * @param int  $attachment_id Attachment ID.
	 * @param bool $is_private    Target state.
	 * @return array<string,string> Errors by path.
	 */
	public function set_privacy( $attachment_id, $is_private ) {
		$file = (string) get_post_meta( $attachment_id, '_wp_attached_file', true );
		if ( ! $is_private && $this->is_protected_path( $file ) ) {
			return array( $file => __( 'Files in protected directories (BuddyBoss, WooCommerce, Easy Digital Downloads) cannot be made public.', 'bm-s3-offload' ) );
		}

		// Attachments that share the file (media translations) share its privacy: the
		// objects belong to one of them, the state is stored for all of them.
		$group  = array_merge( array( (int) $attachment_id ), $this->sharing_attachments( (int) $attachment_id ) );
		$errors = $this->offloader->set_privacy( array_keys( $this->group_items( $group ) ), (bool) $is_private );

		// Store the new state once every object has been moved (a leftover previous copy is
		// reported, but cleaned up later); otherwise the next offload moves files back to the
		// stored state.
		$moved = true;
		foreach ( $this->group_items( $group ) as $item ) {
			if ( (bool) $item['is_private'] !== (bool) $is_private ) {
				$moved = false;
			}
		}
		if ( $moved ) {
			foreach ( $group as $id ) {
				update_post_meta( $id, self::META_PRIVATE, $is_private ? '1' : '0' );
			}
		}
		return $errors;
	}

	/**
	 * Items of a group of attachments.
	 *
	 * @param int[] $attachment_ids Attachment IDs.
	 * @return array<string,array> Items by path.
	 */
	private function group_items( array $attachment_ids ) {
		$items = array();
		foreach ( $attachment_ids as $id ) {
			$items += $this->offloader->items()->get_by_source( Items::SOURCE_POST, (int) $id );
		}
		return $items;
	}

	/**
	 * Item of the attachment's main file.
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return array|null
	 */
	public function main_item( $attachment_id ) {
		$file = (string) get_post_meta( $attachment_id, '_wp_attached_file', true );
		return '' === $file ? null : $this->offloader->items()->get( $file );
	}

	/**
	 * Whether URLs of an item are rewritten to the bucket.
	 *
	 * @param array $item Item.
	 * @return bool
	 */
	private function should_rewrite( array $item ) {
		return $this->offloader->settings()->get( 'rewrite_urls' ) || $item['local_removed'];
	}

	/*
	 * ------------------------------------------------------------------
	 * Operations
	 * ------------------------------------------------------------------
	 */

	/**
	 * Offloads an attachment.
	 *
	 * @param int        $attachment_id Attachment ID.
	 * @param array|null $meta          Metadata.
	 * @param bool       $force         Re-upload unchanged files.
	 * @param bool|null  $remove_local  Remove local copies; null = use setting.
	 * @return array{uploaded:string[],skipped:string[],errors:array<string,string>}
	 */
	public function offload( $attachment_id, $meta = null, $force = false, $remove_local = null ) {
		$attachment_id = (int) $attachment_id;
		$paths         = $this->own_paths( $attachment_id, $this->paths( $attachment_id, $meta ) );
		$result        = $this->offloader->upload( Items::SOURCE_POST, $attachment_id, $paths, $this->is_private( $attachment_id ), $force );

		if ( ! empty( $result['errors'] ) ) {
			$this->add_retry( $attachment_id );
			return $result;
		}

		$this->clear_retry( $attachment_id );

		if ( null === $remove_local ) {
			$remove_local = $this->offloader->settings()->get( 'remove_local' ) || isset( $this->restored[ $attachment_id ] );
		}
		if ( $remove_local && $this->can_remove_local( $attachment_id ) ) {
			$this->offloader->queue_local_removal( $paths );
		}

		return $result;
	}

	/**
	 * Leaves out paths that another attachment with the same main file has
	 * uploaded already (shared files of media translations); they are not
	 * uploaded twice and do not count as errors.
	 *
	 * @param int      $attachment_id Attachment ID.
	 * @param string[] $paths         Relative paths.
	 * @return string[]
	 */
	private function own_paths( $attachment_id, array $paths ) {
		$sharing = null;
		$pending = null;
		foreach ( $this->offloader->items()->get_many( $paths ) as $path => $item ) {
			if ( Items::SOURCE_POST !== $item['source_type'] || (int) $attachment_id === (int) $item['source_id'] ) {
				continue;
			}
			if ( null === $sharing ) {
				$sharing = $this->sharing_attachments( $attachment_id );
				$pending = get_option( self::HANDOVER_OPTION, array() );
			}
			// Also files whose handover from a deleted attachment is still pending.
			if ( in_array( (int) $item['source_id'], $sharing, true ) || ( is_array( $pending ) && isset( $pending[ $path ] ) ) ) {
				$paths = array_diff( $paths, array( $path ) );
			}
		}
		return array_values( $paths );
	}

	/**
	 * Restores all local copies of an attachment.
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return array{downloaded:string[],errors:array<string,string>}
	 */
	public function restore_local( $attachment_id ) {
		return $this->offloader->download( $this->paths( $attachment_id ) );
	}

	/**
	 * Removes all local copies of an offloaded attachment (verified by HEAD requests).
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return string[] Removed paths.
	 */
	public function remove_local( $attachment_id ) {
		if ( ! $this->can_remove_local( $attachment_id ) ) {
			return array();
		}
		return $this->offloader->remove_local( $this->paths( $attachment_id ), true );
	}

	/**
	 * Whether the local copies of an attachment may be removed.
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return bool
	 */
	public function can_remove_local( $attachment_id ) {
		$file    = (string) get_post_meta( $attachment_id, '_wp_attached_file', true );
		$allowed = true;
		foreach ( self::KEEP_LOCAL_DIRS as $dir ) {
			if ( 0 === strpos( $file, $dir ) ) {
				$allowed = false;
			}
		}

		// Protected files are only delivered from the bucket by the matching integration.
		// Without it, the owning plugin serves the local file: keep it.
		if ( ! $this->delivered_from_bucket( $file ) ) {
			$allowed = false;
		}

		/**
		 * Filters whether the local copies of an attachment may be removed.
		 *
		 * @param bool $allowed       Default false for directories of plugins without (active) delivery integration.
		 * @param int  $attachment_id Attachment ID.
		 */
		return (bool) apply_filters( 'bms3o_can_remove_local', $allowed, $attachment_id );
	}

	/**
	 * Moves an attachment back to the local server and deletes its objects.
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return array<string,string> Errors by path; empty on success.
	 */
	public function unoffload( $attachment_id ) {
		$paths    = array_keys( $this->offloader->items()->get_by_source( Items::SOURCE_POST, (int) $attachment_id ) );
		$download = $this->offloader->download( $paths );
		if ( ! empty( $download['errors'] ) ) {
			return $download['errors'];
		}
		// Objects are only deleted while their local copy still exists (another
		// operation could have removed it again since the download).
		return $this->offloader->delete_remote( $paths, true );
	}

