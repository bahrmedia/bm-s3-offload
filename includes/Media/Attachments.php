	/**
	 * The image editor needs a local file: restore it if it was removed.
	 *
	 * @param string       $filepath      Local path or URL.
	 * @param int          $attachment_id Attachment ID.
	 * @param string|int[] $size          Size.
	 * @return string
	 */
	public function filter_edit_path( $filepath, $attachment_id, $size ) {
		if ( is_string( $filepath ) && '' !== $filepath && false === strpos( $filepath, '://' ) && file_exists( $filepath ) ) {
			return $filepath;
		}

		if ( ! $this->restore_temporarily( (int) $attachment_id ) ) {
			return $filepath;
		}

		$local = get_attached_file( $attachment_id );
		if ( 'full' !== $size ) {
			$data = image_get_intermediate_size( $attachment_id, $size );
			if ( $data && ! empty( $data['file'] ) ) {
				$local = path_join( dirname( $local ), $data['file'] );
			}
		}

		return file_exists( $local ) ? $local : $filepath;
	}

	/**
	 * Restores the original image while thumbnails are regenerated (third-party
	 * regeneration and WP-CLI "wp media regenerate").
	 *
	 * @param string|false $path          Original image path.
	 * @param int          $attachment_id Attachment ID.
	 * @return string|false
	 */
	public function filter_original_image_path( $path, $attachment_id ) {
		$cli = defined( 'WP_CLI' ) && WP_CLI;
		if ( ( ! $this->regenerating && ! $cli ) || ! is_string( $path ) || '' === $path || file_exists( $path ) ) {
			return $path;
		}

		$this->restore_temporarily( (int) $attachment_id );
		return $path;
	}

	/**
	 * Marks the start/end of a third-party thumbnail regeneration.
	 *
	 * @param bool $regenerating State.
	 * @return void
	 */
	public function set_regenerating( $regenerating ) {
		$this->regenerating = (bool) $regenerating;
	}

	/**
	 * Restores the local copies of an offloaded attachment for the current
	 * request. If the attachment was bucket-only (or local copies are removed
	 * by setting), all its files - including files created in this request -
	 * are removed again at the end of the request.
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return bool Whether the files are available locally now.
	 */
	private function restore_temporarily( $attachment_id ) {
		$main = $this->main_item( $attachment_id );
		if ( ! $main ) {
			return false;
		}

		$result = $this->restore_local( $attachment_id );
		if ( ! empty( $result['errors'] ) ) {
			return false;
		}

		if ( ( $main['local_removed'] || $this->offloader->settings()->get( 'remove_local' ) ) && $this->can_remove_local( $attachment_id ) ) {
			$this->restored[ $attachment_id ] = true;
			$this->offloader->queue_local_removal( $this->paths( $attachment_id ) );
		}
		return true;
	}

