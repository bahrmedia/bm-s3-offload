<?php
/**
 * Media library integration.
 *
 * @package BahrMedia\S3Offload
 */

namespace BahrMedia\S3Offload\Media;

use BahrMedia\S3Offload\Offloader;
use BahrMedia\S3Offload\Store\Items;

defined( 'ABSPATH' ) || exit;

/**
 * Offloads attachments (original, all sizes, the unscaled original and
 * edit backups) and serves them from the bucket.
 */
final class Attachments {

	const RETRY_OPTION = 'bms3o_retry';

	/**
	 * Upload directories of BuddyBoss photos, documents and videos. Files in
	 * there are protected by BuddyBoss and are therefore stored privately -
	 * also when the BuddyBoss integration is switched off.
	 */
	const PRIVATE_DIRS = array( 'bb_medias/', 'bb_documents/', 'bb_videos/' );
	const MAX_ATTEMPTS = 5;

	/**
	 * Offloader.
	 *
	 * @var Offloader
	 */
	private $offloader;

	/**
	 * True while thumbnails are being regenerated by a third party.
	 *
	 * @var bool
	 */
	private $regenerating = false;

	/**
	 * Attachments that were restored temporarily and must end up bucket-only again.
	 *
	 * @var array<int,true>
	 */
	private $restored = array();

	/**
	 * Constructor.
	 *
	 * @param Offloader $offloader Offloader.
	 */
	public function __construct( Offloader $offloader ) {
		$this->offloader = $offloader;
	}

	/**
	 * Registers hooks.
	 *
	 * @return void
	 */
	public function register() {
		// Upload / edit / delete.
		add_filter( 'wp_update_attachment_metadata', array( $this, 'on_update_metadata' ), 110, 2 );
		add_action( 'delete_attachment', array( $this, 'on_delete' ), 5 );
		add_filter( 'wp_unique_filename', array( $this, 'filter_unique_filename' ), 10, 3 );

		// Delivery.
		add_filter( 'wp_get_attachment_url', array( $this, 'filter_attachment_url' ), 99, 2 );
		add_filter( 'image_downsize', array( $this, 'filter_image_downsize' ), 99, 3 );
		add_filter( 'wp_calculate_image_srcset', array( $this, 'filter_srcset' ), 99, 5 );
		add_filter( 'the_posts', array( $this, 'prime_posts' ), 10, 1 );

		// Local copies on demand.
		add_filter( 'load_image_to_edit_path', array( $this, 'filter_edit_path' ), 5, 3 );
		add_filter( 'wp_get_original_image_path', array( $this, 'filter_original_image_path' ), 5, 2 );

		// Retries.
		add_action( 'bms3o_cron', array( $this, 'retry_failed' ) );
	}

	/*
	 * ------------------------------------------------------------------
	 * Paths
	 * ------------------------------------------------------------------
	 */

	/**
	 * All relative paths of an attachment.
	 *
	 * @param int        $attachment_id Attachment ID.
	 * @param array|null $meta          Metadata (defaults to stored metadata).
	 * @return string[]
	 */
	public function paths( $attachment_id, $meta = null ) {
		$file = (string) get_post_meta( $attachment_id, '_wp_attached_file', true );
		if ( '' === $file || 0 === strpos( $file, '/' ) || false !== strpos( $file, '://' ) || preg_match( '#^[a-zA-Z]:\\\\#', $file ) ) {
			return array(); // Missing, absolute or external file.
		}

		if ( null === $meta ) {
			$meta = wp_get_attachment_metadata( $attachment_id, true );
		}
		$meta  = is_array( $meta ) ? $meta : array();
		$dir   = dirname( $file );
		$dir   = ( '.' === $dir || '' === $dir ) ? '' : $dir . '/';
		$paths = array( $file );

		if ( ! empty( $meta['sizes'] ) && is_array( $meta['sizes'] ) ) {
			foreach ( $meta['sizes'] as $size ) {
				if ( ! empty( $size['file'] ) ) {
					$paths[] = $dir . $size['file'];
				}
			}
		}

		if ( ! empty( $meta['original_image'] ) ) {
			$paths[] = $dir . $meta['original_image'];
		}

		$backups = get_post_meta( $attachment_id, '_wp_attachment_backup_sizes', true );
		if ( is_array( $backups ) ) {
			foreach ( $backups as $backup ) {
				if ( ! empty( $backup['file'] ) ) {
					$paths[] = $dir . $backup['file'];
				}
			}
		}

		/**
		 * Filters the files that belong to an attachment.
		 *
		 * @param string[] $paths         Paths relative to the uploads directory.
		 * @param int      $attachment_id Attachment ID.
		 * @param array    $meta          Attachment metadata.
		 */
		$paths = (array) apply_filters( 'bms3o_attachment_paths', $paths, $attachment_id, $meta );

		return array_values( array_unique( array_filter( $paths, 'strlen' ) ) );
	}

	/**
	 * Whether an attachment is stored as private object.
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return bool
	 */
	public function is_private( $attachment_id ) {
		$file       = (string) get_post_meta( $attachment_id, '_wp_attached_file', true );
		$is_private = false;
		if ( $this->offloader->settings()->get( 'bb_private' ) ) {
			foreach ( self::PRIVATE_DIRS as $dir ) {
				if ( 0 === strpos( $file, $dir ) ) {
					$is_private = true;
					break;
				}
			}
		}

		/**
		 * Filters whether an attachment is stored privately and served with signed URLs only.
		 *
		 * @param bool   $is_private    Default: true for BuddyBoss media directories.
		 * @param int    $attachment_id Attachment ID.
		 * @param string $file          Relative path of the main file.
		 */
		return (bool) apply_filters( 'bms3o_attachment_is_private', $is_private, $attachment_id, $file );
	}

	/**
	 * Item of the attachment's main file.
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return array|null
	 */
	public function main_item( $attachment_id ) {
		$file = (string) get_post_meta( $attachment_id, '_wp_attached_file', true );
		return '' === $file ? null : $this->offloader->items()->get( $file );
	}

	/**
	 * Whether URLs of an item are rewritten to the bucket.
	 *
	 * @param array $item Item.
	 * @return bool
	 */
	private function should_rewrite( array $item ) {
		return $this->offloader->settings()->get( 'rewrite_urls' ) || $item['local_removed'];
	}

	/*
	 * ------------------------------------------------------------------
	 * Operations
	 * ------------------------------------------------------------------
	 */

	/**
	 * Offloads an attachment.
	 *
	 * @param int        $attachment_id Attachment ID.
	 * @param array|null $meta          Metadata.
	 * @param bool       $force         Re-upload unchanged files.
	 * @param bool|null  $remove_local  Remove local copies; null = use setting.
	 * @return array{uploaded:string[],skipped:string[],errors:array<string,string>}
	 */
	public function offload( $attachment_id, $meta = null, $force = false, $remove_local = null ) {
		$attachment_id = (int) $attachment_id;
		$paths         = $this->paths( $attachment_id, $meta );
		$result        = $this->offloader->upload( Items::SOURCE_POST, $attachment_id, $paths, $this->is_private( $attachment_id ), $force );

		if ( ! empty( $result['errors'] ) ) {
			$this->add_retry( $attachment_id );
			return $result;
		}

		$this->clear_retry( $attachment_id );

		if ( null === $remove_local ) {
			$remove_local = $this->offloader->settings()->get( 'remove_local' ) || isset( $this->restored[ $attachment_id ] );
		}
		if ( $remove_local ) {
			$this->offloader->queue_local_removal( $paths );
		}

		return $result;
	}

	/**
	 * Restores all local copies of an attachment.
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return array{downloaded:string[],errors:array<string,string>}
	 */
	public function restore_local( $attachment_id ) {
		return $this->offloader->download( $this->paths( $attachment_id ) );
	}

	/**
	 * Removes all local copies of an offloaded attachment (verified by HEAD requests).
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return string[] Removed paths.
	 */
	public function remove_local( $attachment_id ) {
		return $this->offloader->remove_local( $this->paths( $attachment_id ), true );
	}

	/**
	 * Moves an attachment back to the local server and deletes its objects.
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return array<string,string> Errors by path; empty on success.
	 */
	public function unoffload( $attachment_id ) {
		$paths    = array_keys( $this->offloader->items()->get_by_source( Items::SOURCE_POST, (int) $attachment_id ) );
		$download = $this->offloader->download( $paths );
		if ( ! empty( $download['errors'] ) ) {
			return $download['errors'];
		}
		return $this->offloader->delete_remote( $paths );
	}

	/*
	 * ------------------------------------------------------------------
	 * Hooks: lifecycle
	 * ------------------------------------------------------------------
	 */

	/**
	 * Offloads new and changed files whenever attachment metadata is saved.
	 *
	 * WordPress saves the metadata after every generated size, so only
	 * new or changed files are uploaded on each call.
	 *
	 * @param array|mixed $data          Metadata.
	 * @param int         $attachment_id Attachment ID.
	 * @return array|mixed
	 */
	public function on_update_metadata( $data, $attachment_id ) {
		$settings = $this->offloader->settings();
		if ( ! $settings->get( 'copy_on_upload' ) || ! $settings->is_configured() ) {
			return $data;
		}

		/**
		 * Filters whether an attachment should be offloaded automatically.
		 *
		 * @param bool  $offload       Default true.
		 * @param int   $attachment_id Attachment ID.
		 * @param array $data          Metadata.
		 */
		if ( ! apply_filters( 'bms3o_should_offload_attachment', true, (int) $attachment_id, $data ) ) {
			return $data;
		}

		$this->offload( (int) $attachment_id, is_array( $data ) ? $data : array() );
		return $data;
	}

	/**
	 * Deletes the objects of a deleted attachment.
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return void
	 */
	public function on_delete( $attachment_id ) {
		$items = $this->offloader->items()->get_by_source( Items::SOURCE_POST, (int) $attachment_id );
		if ( empty( $items ) ) {
			return;
		}

		$paths = array_keys( $items );
		$this->offloader->unqueue_local_removal( $paths );

		if ( $this->offloader->settings()->get( 'delete_remote' ) && $this->offloader->settings()->is_configured() ) {
			$this->offloader->delete_remote( $paths );
		}
		// Forget remaining items (delete disabled or failed): the attachment is gone.
		$this->offloader->items()->delete( $paths );
		$this->clear_retry( (int) $attachment_id );
	}

	/**
	 * Keeps new file names unique when earlier files with the same name only
	 * exist in the bucket (local copy removed). Otherwise WordPress would
	 * reuse the name and overwrite the other file's object.
	 *
	 * @param string $filename File name chosen by WordPress.
	 * @param string $ext      Extension (with dot).
	 * @param string $dir      Absolute target directory.
	 * @return string
	 */
	public function filter_unique_filename( $filename, $ext, $dir ) {
		$base = $this->offloader->uploads()['basedir'];
		$dir  = untrailingslashit( wp_normalize_path( (string) $dir ) );
		if ( $dir !== $base && 0 !== strpos( $dir, $base . '/' ) ) {
			return $filename; // Not inside the uploads directory.
		}
		$relative_dir = $dir === $base ? '' : substr( $dir, strlen( $base ) + 1 ) . '/';

		$info      = pathinfo( $filename );
		$name      = $info['filename'];
		$extension = isset( $info['extension'] ) ? '.' . $info['extension'] : '';
		$candidate = $filename;
		$number    = 1;

		while ( $this->name_taken( $relative_dir, $candidate ) || file_exists( $dir . '/' . $candidate ) ) {
			$candidate = $name . '-' . $number . $extension;
			++$number;
		}

		return $candidate;
	}

	/**
	 * Whether a file name (or one of its image size variants) is used by an offloaded item.
	 *
	 * @param string $relative_dir Relative directory with trailing slash ('' for the root).
	 * @param string $filename     File name.
	 * @return bool
	 */
	private function name_taken( $relative_dir, $filename ) {
		$name   = pathinfo( $filename, PATHINFO_FILENAME );
		$items  = $this->offloader->items()->get_with_prefix( $relative_dir . $name, 500 );
		$prefix = preg_quote( $relative_dir . $name, '#' );

		foreach ( array_keys( $items ) as $path ) {
			// The file itself, or a size variant like "name-300x200.jpg" / "name-scaled.jpg".
			if ( $path === $relative_dir . $filename || preg_match( '#^' . $prefix . '(?:-\d+x\d+|-scaled|-rotated)\.[^./]+$#i', $path ) ) {
				return true;
			}
		}
		return false;
	}

	/*
	 * ------------------------------------------------------------------
	 * Hooks: delivery
	 * ------------------------------------------------------------------
	 */

	/**
	 * Attachment URL.
	 *
	 * @param string $url           Local URL.
	 * @param int    $attachment_id Attachment ID.
	 * @return string
	 */
	public function filter_attachment_url( $url, $attachment_id ) {
		$item = $this->main_item( (int) $attachment_id );
		if ( ! $item || ! $this->should_rewrite( $item ) ) {
			return $url;
		}
		$new = $this->offloader->url( $item );
		return '' === $new ? $url : $new;
	}

	/**
	 * Builds image URLs from the bucket item of the requested size.
	 *
	 * This also keeps signed URLs intact, which WordPress' own basename
	 * replacement in image_downsize() would break.
	 *
	 * @param array|false  $downsize      Short-circuit value.
	 * @param int          $attachment_id Attachment ID.
	 * @param string|int[] $size          Size name or [width, height].
	 * @return array|false
	 */
	public function filter_image_downsize( $downsize, $attachment_id, $size ) {
		if ( false !== $downsize ) {
			return $downsize;
		}

		$main = $this->main_item( (int) $attachment_id );
		if ( ! $main || ! $this->should_rewrite( $main ) || ! $this->offloader->can_deliver( $main ) ) {
			return false;
		}

		$intermediate = image_get_intermediate_size( $attachment_id, $size );
		if ( $intermediate && ! empty( $intermediate['path'] ) ) {
			$item = $this->offloader->items()->get( $intermediate['path'] );
			$url = $item ? $this->offloader->url( $item ) : '';
			if ( '' !== $url ) {
				return array( $url, (int) $intermediate['width'], (int) $intermediate['height'], true );
			}
		}

		if ( ! wp_attachment_is_image( $attachment_id ) ) {
			return false;
		}

		$meta   = wp_get_attachment_metadata( $attachment_id );
		$width  = isset( $meta['width'] ) ? (int) $meta['width'] : 0;
		$height = isset( $meta['height'] ) ? (int) $meta['height'] : 0;
		if ( $width && $height ) {
			list( $width, $height ) = image_constrain_size_for_editor( $width, $height, $size );
		}

		$url = $this->offloader->url( $main );
		return '' === $url ? false : array( $url, $width, $height, false );
	}

	/**
	 * Rewrites srcset candidates.
	 *
	 * @param array  $sources       Sources keyed by width.
	 * @param array  $size_array    Requested size.
	 * @param string $image_src     Image src.
	 * @param array  $image_meta    Image metadata.
	 * @param int    $attachment_id Attachment ID.
	 * @return array
	 */
	public function filter_srcset( $sources, $size_array, $image_src, $image_meta, $attachment_id ) {
		if ( ! is_array( $sources ) || empty( $sources ) ) {
			return $sources;
		}

		$main = $this->main_item( (int) $attachment_id );
		if ( ! $main || ! $this->should_rewrite( $main ) || ! $this->offloader->can_deliver( $main ) ) {
			return $sources;
		}

		$dir   = dirname( $main['path'] );
		$dir   = '.' === $dir ? '' : $dir . '/';
		$paths = array();
		foreach ( $sources as $width => $source ) {
			$paths[ $width ] = $dir . wp_basename( strtok( $source['url'], '?' ) );
		}

		$items = $this->offloader->items()->get_many( $paths );
		foreach ( $paths as $width => $path ) {
			$url = isset( $items[ $path ] ) ? $this->offloader->url( $items[ $path ] ) : '';
			if ( '' !== $url ) {
				$sources[ $width ]['url'] = $url;
			}
		}

		return $sources;
	}

	/**
	 * Loads the items of all attachments in a query result with one query.
	 *
	 * @param \WP_Post[]|mixed $posts Posts.
	 * @return \WP_Post[]|mixed
	 */
	public function prime_posts( $posts ) {
		if ( ! is_array( $posts ) || empty( $posts ) ) {
			return $posts;
		}

		$ids      = array();
		$expected = array();
		foreach ( $posts as $post ) {
			if ( $post instanceof \WP_Post && 'attachment' === $post->post_type ) {
				$ids[] = $post->ID;
				$file  = (string) get_post_meta( $post->ID, '_wp_attached_file', true );
				if ( '' !== $file ) {
					$expected[] = $file;
				}
			}
		}

		if ( ! empty( $ids ) ) {
			$this->offloader->items()->prime( Items::SOURCE_POST, $ids, $expected );
		}

		return $posts;
	}

	/*
	 * ------------------------------------------------------------------
	 * Hooks: local copies on demand
	 * ------------------------------------------------------------------
	 */

	/**
	 * The image editor needs a local file: restore it if it was removed.
	 *
	 * @param string       $filepath      Local path or URL.
	 * @param int          $attachment_id Attachment ID.
	 * @param string|int[] $size          Size.
	 * @return string
	 */
	public function filter_edit_path( $filepath, $attachment_id, $size ) {
		if ( is_string( $filepath ) && '' !== $filepath && false === strpos( $filepath, '://' ) && file_exists( $filepath ) ) {
			return $filepath;
		}

		if ( ! $this->restore_temporarily( (int) $attachment_id ) ) {
			return $filepath;
		}

		$local = get_attached_file( $attachment_id );
		if ( 'full' !== $size ) {
			$data = image_get_intermediate_size( $attachment_id, $size );
			if ( $data && ! empty( $data['file'] ) ) {
				$local = path_join( dirname( $local ), $data['file'] );
			}
		}

		return file_exists( $local ) ? $local : $filepath;
	}

	/**
	 * Restores the original image while thumbnails are regenerated (third-party
	 * regeneration and WP-CLI "wp media regenerate").
	 *
	 * @param string|false $path          Original image path.
	 * @param int          $attachment_id Attachment ID.
	 * @return string|false
	 */
	public function filter_original_image_path( $path, $attachment_id ) {
		$cli = defined( 'WP_CLI' ) && WP_CLI;
		if ( ( ! $this->regenerating && ! $cli ) || ! is_string( $path ) || '' === $path || file_exists( $path ) ) {
			return $path;
		}

		$this->restore_temporarily( (int) $attachment_id );
		return $path;
	}

	/**
	 * Marks the start/end of a third-party thumbnail regeneration.
	 *
	 * @param bool $regenerating State.
	 * @return void
	 */
	public function set_regenerating( $regenerating ) {
		$this->regenerating = (bool) $regenerating;
	}

	/**
	 * Restores the local copies of an offloaded attachment for the current
	 * request. If the attachment was bucket-only (or local copies are removed
	 * by setting), all its files - including files created in this request -
	 * are removed again at the end of the request.
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return bool Whether the files are available locally now.
	 */
	private function restore_temporarily( $attachment_id ) {
		$main = $this->main_item( $attachment_id );
		if ( ! $main ) {
			return false;
		}

		$result = $this->restore_local( $attachment_id );
		if ( ! empty( $result['errors'] ) ) {
			return false;
		}

		if ( $main['local_removed'] || $this->offloader->settings()->get( 'remove_local' ) ) {
			$this->restored[ $attachment_id ] = true;
			$this->offloader->queue_local_removal( $this->paths( $attachment_id ) );
		}
		return true;
	}

	/*
	 * ------------------------------------------------------------------
	 * Retries
	 * ------------------------------------------------------------------
	 */

	/**
	 * Remembers a failed attachment.
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return void
	 */
	private function add_retry( $attachment_id ) {
		$retry = get_option( self::RETRY_OPTION, array() );
		$retry = is_array( $retry ) ? $retry : array();
		if ( ! isset( $retry[ $attachment_id ] ) && count( $retry ) >= 1000 ) {
			return; // Bulk tools will catch the rest.
		}
		$retry[ $attachment_id ] = isset( $retry[ $attachment_id ] ) ? (int) $retry[ $attachment_id ] : 0;
		update_option( self::RETRY_OPTION, $retry, false );
	}

	/**
	 * Forgets a failed attachment.
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return void
	 */
	private function clear_retry( $attachment_id ) {
		$retry = get_option( self::RETRY_OPTION, array() );
		if ( is_array( $retry ) && isset( $retry[ $attachment_id ] ) ) {
			unset( $retry[ $attachment_id ] );
			update_option( self::RETRY_OPTION, $retry, false );
		}
	}

	/**
	 * Cron: retries failed uploads.
	 *
	 * @return void
	 */
	public function retry_failed() {
		if ( ! $this->offloader->settings()->is_configured() ) {
			return;
		}

		$retry = get_option( self::RETRY_OPTION, array() );
		if ( ! is_array( $retry ) || empty( $retry ) ) {
			return;
		}

		foreach ( array_slice( $retry, 0, 25, true ) as $attachment_id => $attempts ) {
			if ( ! get_post( $attachment_id ) || $attempts + 1 >= self::MAX_ATTEMPTS ) {
				unset( $retry[ $attachment_id ] );
				continue;
			}
			$result = $this->offloader->upload( Items::SOURCE_POST, (int) $attachment_id, $this->paths( (int) $attachment_id ), $this->is_private( (int) $attachment_id ) );
			if ( empty( $result['errors'] ) ) {
				unset( $retry[ $attachment_id ] );
				if ( $this->offloader->settings()->get( 'remove_local' ) ) {
					$this->offloader->queue_local_removal( $this->paths( (int) $attachment_id ) );
				}
			} else {
				$retry[ $attachment_id ] = $attempts + 1;
			}
		}

		update_option( self::RETRY_OPTION, $retry, false );
	}

	/**
	 * IDs of attachments waiting for a retry.
	 *
	 * @return int[]
	 */
	public function pending_retries() {
		$retry = get_option( self::RETRY_OPTION, array() );
		return is_array( $retry ) ? array_map( 'intval', array_keys( $retry ) ) : array();
	}
}
