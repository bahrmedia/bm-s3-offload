	 * ------------------------------------------------------------------
	 * Hooks: lifecycle
	 * ------------------------------------------------------------------
	 */

	/**
	 * Offloads new and changed files whenever attachment metadata is saved.
	 *
	 * WordPress saves the metadata after every generated size, so only
	 * new or changed files are uploaded on each call.
	 *
	 * @param array|mixed $data          Metadata.
	 * @param int         $attachment_id Attachment ID.
	 * @return array|mixed
	 */
	public function on_update_metadata( $data, $attachment_id ) {
		$settings = $this->offloader->settings();
		if ( ! $settings->get( 'copy_on_upload' ) || ! $settings->is_configured() ) {
			return $data;
		}

		/**
		 * Filters whether an attachment should be offloaded automatically.
		 *
		 * @param bool  $offload       Default true.
		 * @param int   $attachment_id Attachment ID.
		 * @param array $data          Metadata.
		 */
		if ( ! apply_filters( 'bms3o_should_offload_attachment', true, (int) $attachment_id, $data ) ) {
			return $data;
		}

		$data = is_array( $data ) ? $data : array();
		if ( $this->should_defer( (int) $attachment_id, $data ) ) {
			if ( ! wp_next_scheduled( self::ASYNC_HOOK, array( (int) $attachment_id ) ) ) {
				// Delayed, so the upload request can finish creating all image sizes first.
				wp_schedule_single_event( time() + MINUTE_IN_SECONDS, self::ASYNC_HOOK, array( (int) $attachment_id ) );
			}
			return $data;
		}

		$this->offload( (int) $attachment_id, $data );
		return $data;
	}

	/**
	 * Whether an upload is too large to be offloaded within the upload request.
	 *
	 * @param int   $attachment_id Attachment ID.
	 * @param array $meta          Metadata.
	 * @return bool
	 */
	private function should_defer( $attachment_id, array $meta ) {
		if ( wp_doing_cron() || ( defined( 'WP_CLI' ) && WP_CLI ) ) {
			return false;
		}

		$size = 0;
		foreach ( $this->paths( $attachment_id, $meta ) as $path ) {
			$file  = $this->offloader->absolute( $path );
			$size += is_file( $file ) ? (int) filesize( $file ) : 0;
		}

		/**
		 * Filters the size (bytes) above which attachments are offloaded in the background.
		 *
		 * @param int $threshold     Default 64 MiB.
		 * @param int $attachment_id Attachment ID.
		 */
		return $size > (int) apply_filters( 'bms3o_async_threshold', self::ASYNC_THRESHOLD, $attachment_id );
	}

	/**
	 * Cron: offloads a large attachment.
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return void
	 */
	public function offload_in_background( $attachment_id ) {
		if ( ! get_post( $attachment_id ) || ! $this->offloader->settings()->is_configured() ) {
			return;
		}
		if ( function_exists( 'set_time_limit' ) ) {
			set_time_limit( 0 ); // phpcs:ignore Squiz.PHP.DiscouragedFunctions.Discouraged -- Large uploads in a cron request.
		}
		$this->offload( (int) $attachment_id );
	}

	/**
	 * Deletes the objects of a deleted attachment.
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return void
	 */
	public function on_delete( $attachment_id ) {
		$attachment_id = (int) $attachment_id;
		$this->clear_retry( $attachment_id );
		$items = $this->offloader->items()->get_by_source( Items::SOURCE_POST, $attachment_id );
		if ( empty( $items ) ) {
			return;
		}

		// Files that another attachment still uses (e.g. a media translation of WPML or
		// Polylang) are kept: their items are handed over to that attachment. They are
		// never deleted, even when the handover fails – it is then retried hourly.
		$paths = array_keys( $items );
		$file  = (string) get_post_meta( $attachment_id, '_wp_attached_file', true );
		foreach ( $this->sharing_attachments( $attachment_id ) as $other ) {
			$shared = $this->shared_paths( $paths, $other );
			if ( empty( $shared ) ) {
				continue;
			}
			$paths = array_values( array_diff( $paths, $shared ) );
			$this->add_handover( $this->offloader->items()->reassign( $shared, Items::SOURCE_POST, $other ), $file );
			$this->adopt_privacy( $other, $items[ $shared[0] ] );
			if ( empty( $paths ) ) {
				return;
			}
		}

		$this->forget_files( $paths, $items );
	}

	/**
	 * Paths of an attachment that another attachment uses as well.
	 *
	 * @param string[] $paths Paths of the attachment.
	 * @param int      $other Other attachment.
	 * @return string[]
	 */
	private function shared_paths( array $paths, $other ) {
		$shared = array_intersect( $paths, $this->paths( $other ) );
		foreach ( $paths as $path ) {
			// WebP/AVIF copies of shared files are shared as well (paths() lists them only for their owner).
			if ( preg_match( '/^(.+)\.(webp|avif)$/', $path, $m ) && in_array( $m[1], $shared, true ) ) {
				$shared[] = $path;
			}
		}
		return array_values( array_unique( $shared ) );
	}

	/**
	 * Stores the privacy of handed-over objects for the attachment that owns
	 * them now, so that later privacy syncs do not move them.
	 *
	 * @param int   $attachment_id New owner.
	 * @param array $item          One of the handed-over items.
	 * @return void
	 */
	private function adopt_privacy( $attachment_id, array $item ) {
		if ( $this->is_private( $attachment_id ) !== (bool) $item['is_private'] ) {
			update_post_meta( $attachment_id, self::META_PRIVATE, $item['is_private'] ? '1' : '0' );
		}
	}

	/**
	 * Deletes the objects (if set) and items of files nobody uses any more.
	 *
	 * @param string[]            $paths Relative paths.
	 * @param array<string,array> $items Items by path.
	 * @return void
	 */
	private function forget_files( array $paths, array $items ) {
		$this->offloader->unqueue_local_removal( $paths );

		if ( $this->offloader->settings()->get( 'delete_remote' ) && $this->offloader->settings()->is_configured() ) {
			// Objects that could not be deleted are retried by the hourly cleanup.
			$orphans = array();
			foreach ( array_keys( $this->offloader->delete_remote( $paths ) ) as $path ) {
				$orphans[] = array( $items[ $path ]['bucket'], $items[ $path ]['object_key'], $path );
			}
			if ( ! empty( $orphans ) ) {
				$this->offloader->queue_orphans( $orphans );
			}
		}
		// Forget remaining items: the attachment is gone.
		$this->offloader->items()->delete( $paths );
	}

	/**
	 * Other attachments that use the same main file, e.g. media translations
	 * of WPML or Polylang.
	 *
	 * @param int $attachment_id Attachment ID.
	 * @return int[] Attachment IDs, oldest first.
	 */
	public function sharing_attachments( $attachment_id ) {
		return $this->attachments_with_file( (string) get_post_meta( (int) $attachment_id, '_wp_attached_file', true ), (int) $attachment_id );
	}

	/**
	 * Attachments whose main file is the given file.
	 *
	 * @param string $file    Relative path of the main file.
	 * @param int    $exclude Attachment ID to leave out.
	 * @return int[] Attachment IDs, oldest first.
	 */
	private function attachments_with_file( $file, $exclude = 0 ) {
		global $wpdb;
		if ( '' === (string) $file ) {
			return array();
		}
		// phpcs:ignore WordPress.DB.DirectDatabaseQuery
		$ids = $wpdb->get_col( $wpdb->prepare( "SELECT post_id FROM {$wpdb->postmeta} WHERE meta_key = '_wp_attached_file' AND meta_value = %s AND post_id <> %d ORDER BY post_id ASC", (string) $file, (int) $exclude ) );
		return array_map( 'intval', (array) $ids );
	}

	/**
	 * Keeps new file names unique when earlier files with the same name only
	 * exist in the bucket (local copy removed). Otherwise WordPress would
	 * reuse the name and overwrite the other file's object.
	 *
	 * @param string $filename File name chosen by WordPress.
	 * @param string $ext      Extension (with dot).
	 * @param string $dir      Absolute target directory.
	 * @return string
	 */
	public function filter_unique_filename( $filename, $ext, $dir ) {
		$base = $this->offloader->uploads()['basedir'];
		$dir  = untrailingslashit( wp_normalize_path( (string) $dir ) );
		if ( $dir !== $base && 0 !== strpos( $dir, $base . '/' ) ) {
			return $filename; // Not inside the uploads directory.
		}
		$relative_dir = $dir === $base ? '' : substr( $dir, strlen( $base ) + 1 ) . '/';

		$info      = pathinfo( $filename );
		$name      = $info['filename'];
		$extension = isset( $info['extension'] ) ? '.' . $info['extension'] : '';

		// One indexed query for all candidates ("name", "name-1", "name-2", ...).
		$taken     = array_keys( $this->offloader->items()->get_with_prefix( $relative_dir . $name ) );
		$candidate = $filename;
		$number    = 1;

		while ( $this->name_taken( $taken, $relative_dir, $candidate ) || file_exists( $dir . '/' . $candidate ) ) {
			$candidate = $name . '-' . $number . $extension;
			++$number;
		}

		return $candidate;
	}

	/**
	 * Whether a file name (or one of its image size variants) is used by an offloaded item.
	 *
	 * @param string[] $taken        Offloaded paths starting with the base name.
	 * @param string   $relative_dir Relative directory with trailing slash ('' for the root).
	 * @param string   $filename     File name.
	 * @return bool
	 */
	private function name_taken( array $taken, $relative_dir, $filename ) {
		$prefix = preg_quote( $relative_dir . pathinfo( $filename, PATHINFO_FILENAME ), '#' );
		foreach ( $taken as $path ) {
			// The file itself, or a size variant like "name-300x200.jpg" / "name-scaled.jpg".
			if ( $path === $relative_dir . $filename || preg_match( '#^' . $prefix . '(?:-\\d+x\\d+|-scaled|-rotated)\\.[^./]+$#i', $path ) ) {
				return true;
			}
		}
		return false;
	}

